import AppKit

/// Polls the clipboard and records copies into the "Recent" tab.
final class ClipboardWatcher {
    private let store: ShelfStore
    private let settings: AppSettings
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    /// Password managers and similar apps whose copies are never recorded.
    private let excludedBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal"
    ]

    /// Types apps set to say "don't keep this in clipboard history" (nspasteboard.org).
    private let skipTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    init(store: ShelfStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        guard settings.clipboardHistory, pb.changeCount != store.lastOwnChangeCount else { return }
        let types = pb.types ?? []
        if skipTypes.contains(where: { types.contains($0) }) { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, excludedBundleIDs.contains(app) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            urls.prefix(5).forEach { store.add(url: $0, recent: true) }
        } else if ShelfStore.hasImage(pb), let image = NSImage(pasteboard: pb) {
            store.addImage(image, title: "Copied image", recent: true)
        } else if let string = pb.string(forType: .string) {
            store.addText(string, recent: true)
        }
    }
}
